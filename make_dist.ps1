# Builds the APImageIO beta-tester package:  dist\APImageIO_<version>.zip
#
#   1. Release build (LightWave must be closed - it locks APImageIO.p)
#   2. Regression harness (tests\run_tests.bat) must pass
#   3. Checks: version in src\apimageio_version.h matches README / release
#      notes, feedback address filled in, every sample present, and the .p
#      imports only Windows system DLLs (testers install nothing else)
#   4. Stages Plugins\ Samples\ README.txt RELEASE_NOTES.txt Cryptomatte.md
#   5. Keeps APImageIO.pdb + .p in dist\symbols\<version>\ (NOT shipped) for
#      crash dumps
#
# Samples are generated by tools\mk_samples.py into dist_src\Samples.

$ErrorActionPreference = 'Stop'
$root    = $PSScriptRoot
$vsroot  = 'E:\Microsoft\Visual Studio IDE'
$msbuild = "$vsroot\MSBuild\Current\Bin\MSBuild.exe"
$vcvars  = "$vsroot\VC\Auxiliary\Build\vcvars64.bat"

function Fail([string]$msg) { Write-Host "ERROR: $msg" -ForegroundColor Red; exit 1 }

# --- version, from the source so the plugin and the package always agree ---
$vh = Get-Content -Raw (Join-Path $root 'src\apimageio_version.h')
if ($vh -notmatch '#define APIMAGEIO_VERSION\s+"([^"]+)"') { Fail 'APIMAGEIO_VERSION not found in src\apimageio_version.h' }
$version = $Matches[1]
Write-Host "APImageIO $version"

# --- build ---
& $msbuild (Join-Path $root 'APImageIO.vcxproj') -p:Configuration=Release -p:Platform=x64 -v:minimal -nologo
if ($LASTEXITCODE -ne 0) { Fail 'Build failed (if LNK1104 on APImageIO.p: close LightWave and retry).' }
$plugin = Join-Path $root 'bin\Release\APImageIO.p'

# --- tests ---
& cmd /c (Join-Path $root 'tests\run_tests.bat')
if ($LASTEXITCODE -ne 0) { Fail "Regression harness: exit $LASTEXITCODE (failed checks, or 90+ = setup error)." }

# --- content checks ---
$dsrc   = Join-Path $root 'dist_src'
$readme = Join-Path $dsrc 'README.txt'
$notes  = Join-Path $dsrc 'RELEASE_NOTES.txt'
foreach ($f in @($readme, $notes)) {
    $t = Get-Content -Raw $f
    if ($t -notmatch [regex]::Escape($version)) { Fail "$(Split-Path -Leaf $f) does not mention version $version." }
    if ($t -match '<<FEEDBACK ADDRESS>>')     { Fail "Fill in the feedback address in $(Split-Path -Leaf $f)." }
}
if ((Get-Content -Raw (Join-Path $root 'CHANGELOG.md')) -notmatch [regex]::Escape("[$version]")) {
    Fail "CHANGELOG.md has no [$version] entry."
}

$samples = @('EXR_Blender_Multilayer_DWAA.exr', 'EXR_BBox_Crop_1920x1080.exr', 'EXR_Luminance_Y.exr',
             'PNG16_Smooth_Gradient.png', 'WebP_Sample.webp', 'AVIF_Alpha_Sample.avif',
             'JXL_Sample.jxl', 'DPX_Sample.dpx', 'SVG_Wide_4to1.svg',
             'Krita_Sample.kra', 'OpenRaster_Sample.ora')
foreach ($s in $samples) {
    if (-not (Test-Path (Join-Path $dsrc "Samples\$s"))) { Fail "Missing Samples\$s - run: python tools\mk_samples.py" }
}

# Only Windows system DLLs may be imported (everything else is static).
$deps = & cmd /c "`"$vcvars`" >nul && dumpbin /nologo /dependents `"$plugin`"" |
        Select-String '^\s+(\S+\.dll)\s*$' | ForEach-Object { $_.Matches[0].Groups[1].Value }
$allowed = @('KERNEL32.dll', 'bcrypt.dll', 'WS2_32.dll', 'ADVAPI32.dll', 'USER32.dll', 'ole32.dll', 'SHELL32.dll')
$extra = $deps | Where-Object { $allowed -notcontains $_ }
if (-not $deps)  { Fail 'dumpbin found no imports - could not check dependencies.' }
if ($extra)      { Fail "APImageIO.p imports non-system DLLs: $($extra -join ', ')" }
Write-Host "Imports : $($deps -join ', ')"

# --- stage ---
$name  = "APImageIO_$version"
$dist  = Join-Path $root 'dist'
$stage = Join-Path $dist $name
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory -Force (Join-Path $stage 'Plugins') | Out-Null
New-Item -ItemType Directory -Force (Join-Path $stage 'Samples') | Out-Null

Copy-Item $plugin                                   (Join-Path $stage 'Plugins')
foreach ($s in $samples) { Copy-Item (Join-Path $dsrc "Samples\$s") (Join-Path $stage 'Samples') }
Copy-Item $readme                                   $stage
Copy-Item $notes                                    $stage
Copy-Item (Join-Path $root 'CRYPTOMATTE.md')        (Join-Path $stage 'Cryptomatte.md')

# --- symbols (kept, not shipped) ---
$sym = Join-Path $dist "symbols\$version"
New-Item -ItemType Directory -Force $sym | Out-Null
Copy-Item (Join-Path $root 'bin\Release\APImageIO.pdb') $sym -Force
Copy-Item $plugin                                       $sym -Force

# --- zip ---
$zip = Join-Path $dist "$name.zip"
if (Test-Path $zip) { Remove-Item -Force $zip }
Compress-Archive -Path $stage -DestinationPath $zip
$hash = (Get-FileHash -Algorithm SHA256 $zip).Hash

Write-Host ''
Write-Host "Package : $zip" -ForegroundColor Green
Write-Host "SHA-256 : $hash"
Get-ChildItem -Recurse $stage -File | ForEach-Object { '  ' + $_.FullName.Substring($stage.Length + 1) + "  ($($_.Length) bytes)" }
